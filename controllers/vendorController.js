exports.updateVendor = async (req, res) => {
    try {
        const { id } = req.params;
        const updates = req.body;

        console.log('🔄 Updating vendor:', id, updates);

        // Check if vendor exists
        const [vendors] = await db.execute('SELECT id FROM vendors WHERE id = ?', [id]);
        if (vendors.length === 0) {
            return res.status(404).json({ 
                success: false, 
                message: 'Vendor not found' 
            });
        }

        // Check email if being updated
        if (updates.email) {
            const [existing] = await db.execute('SELECT id FROM vendors WHERE email = ? AND id != ?', [updates.email, id]);
            if (existing.length > 0) {
                return res.status(400).json({ 
                    success: false, 
                    message: 'Email already exists' 
                });
            }
        }

        const fields = [];
        const values = [];

        Object.keys(updates).forEach(key => {
            if (updates[key] !== undefined && updates[key] !== null) {
                fields.push(`${key} = ?`);
                values.push(updates[key]);
            }
        });

        if (fields.length === 0) {
            return res.status(400).json({ 
                success: false, 
                message: 'No fields to update' 
            });
        }

        values.push(id);
        const query = `UPDATE vendors SET ${fields.join(', ')}, updated_at = CURRENT_TIMESTAMP WHERE id = ?`;

        const [result] = await db.execute(query, values);

        if (result.affectedRows === 0) {
            return res.status(404).json({ 
                success: false, 
                message: 'Vendor not found' 
            });
        }

        res.json({ 
            success: true, 
            message: 'Vendor updated successfully' 
        });
    } catch (error) {
        console.error('❌ Update vendor error:', error);
        res.status(500).json({ 
            success: false, 
            message: 'Failed to update vendor',
            error: error.message 
        });
    }
};

