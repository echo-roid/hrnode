const db = require('../config/db');

// Get all vendors
exports.getAllVendors = async (req, res) => {
    try {
        const { page = 1, limit = 10, search } = req.query;
        const pageNum = parseInt(page);
        const limitNum = parseInt(limit);
        const offset = (pageNum - 1) * limitNum;

        // Build WHERE clause
        let whereClause = 'WHERE 1=1';
        const params = [];

        if (search) {
            whereClause += ` AND (vendor_name LIKE ? OR email LIKE ? OR contact_person LIKE ?)`;
            const searchParam = `%${search}%`;
            params.push(searchParam, searchParam, searchParam);
        }

        // Use template literals for LIMIT and OFFSET
        const query = `SELECT * FROM vendors ${whereClause} ORDER BY created_at DESC LIMIT ${limitNum} OFFSET ${offset}`;
        
        console.log('🔍 Executing query:', query);
        console.log('📊 Query parameters:', params);

        const [vendors] = await db.execute(query, params);
        
        // Get total count
        const countQuery = `SELECT COUNT(*) as total FROM vendors ${whereClause}`;
        const [countResult] = await db.execute(countQuery, params);
        const total = countResult[0].total;

        res.json({
            success: true,
            data: vendors,
            pagination: {
                page: pageNum,
                limit: limitNum,
                total,
                pages: Math.ceil(total / limitNum)
            }
        });
    } catch (error) {
        console.error('❌ Get vendors error:', error);
        res.status(500).json({ 
            success: false, 
            message: 'Failed to fetch vendors',
            error: error.message
        });
    }
};


